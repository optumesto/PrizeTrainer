// German type names for Energy, as printed on German cards.
const deI18nTypes = { Grass: 'Pflanze', Fire: 'Feuer', Water: 'Wasser', Lightning: 'Elektro', Psychic: 'Psycho', Fighting: 'Kampf', Darkness: 'Finsternis', Metal: 'Metall', Dragon: 'Drache', Colorless: 'Farblos', Fairy: 'Fee' };
// As the first half of an Energy name: Pflanzen-Energie, Feen-Energie.
const deI18nTypesE = Object.assign({}, deI18nTypes, { Grass: 'Pflanzen', Dragon: 'Drachen', Fairy: 'Feen' });
const deI18nMon = ['Januar', 'Februar', 'März', 'April', 'Mai', 'Juni', 'Juli', 'August', 'September', 'Oktober', 'November', 'Dezember'];
const deI18nMon3 = ['Jan.', 'Feb.', 'März', 'Apr.', 'Mai', 'Juni', 'Juli', 'Aug.', 'Sept.', 'Okt.', 'Nov.', 'Dez.'];
/** English dates and 12 hour times inside a German string: "Nov 12, 2025" is "12. Nov. 2025", "3:05 PM" is "15:05". */
function deI18nDate(s) {
  const E = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
  const M = E.join('|'), S = E.map(m => m.slice(0, 3)).join('|');
  const full = m => deI18nMon[E.indexOf(m)], short = m => deI18nMon3[E.findIndex(x => x.startsWith(m))];
  return String(s)
    .replace(new RegExp(`\\b(${S}) (\\d{1,2}), (\\d{4})\\b`, 'g'), (m, mo, d, y) => `${d}. ${short(mo)} ${y}`)
    .replace(new RegExp(`\\b(\\d{1,2}) (${M}) (\\d{4})\\b`, 'g'), (m, d, mo, y) => `${d}. ${full(mo)} ${y}`)
    .replace(new RegExp(`\\b(${M}) (\\d{4})\\b`, 'g'), (m, mo, y) => `${full(mo)} ${y}`)
    .replace(new RegExp(`\\b(\\d{1,2}) (${S}) (\\d{4})\\b`, 'g'), (m, d, mo, y) => `${d}. ${short(mo)} ${y}`)
    .replace(new RegExp(`\\b(${S}) (\\d{1,2})\\b`, 'g'), (m, mo, d) => `${d}. ${short(mo)}`)
    .replace(new RegExp(`\\b(\\d{1,2}) (${S})\\b`, 'g'), (m, d, mo) => `${d}. ${short(mo)}`)
    .replace(/\b(\d{1,2}):(\d{2}) ?([AP]M)\b/g, (m, h, mi, ap) => ((+h % 12) + (ap === 'PM' ? 12 : 0)) + ':' + mi)
    // "seit 6. Nov.." at the end of a sentence: one stop is enough.
    .replace(/\b(Jan|Feb|Apr|Aug|Sept|Okt|Nov|Dez)\.\.(?!\.)/g, '$1.');
}
/** True when a captured value runs on into another sentence, so the pattern should leave it to the sentence split. */
function deI18nSent(x) { return /[.!?] \S/.test(String(x)); }
/** "1st" as "1.". */
function deI18nOrd(p) { return String(p).replace(/^(\d+)(?:st|nd|rd|th)$/, '$1.'); }
/** Every pattern goes through this: $1 and so on filled in, then dates and times put into German. */
function deI18nWrap(r) {
  if (typeof r === 'function') return function () { const x = r.apply(null, arguments); return x == null ? null : deI18nDate(x); };
  return function () { const g = arguments; return deI18nDate(String(r).replace(/\$(\d)/g, (x, i) => g[+i] == null ? '' : g[+i])); };
}
/** "Today, 3:00 PM", "Yesterday, ..." or a date, as the grade history writes them; null for anything else. */
function deI18nWhen(w) {
  const m = /^(Today|Yesterday), (.+)$/.exec(w);
  if (m) return (m[1] === 'Today' ? 'Heute, ' : 'Gestern, ') + m[2];
  return /^(?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) \d{1,2}(?:, \d{4})?$/.test(w) ? w : null;
}
/** The puzzle streak words: "3 Siege in Folge, 4 Tage in Folge". */
function deI18nRuns(s) {
  return String(s).replace(/(\d+) wins in a row/g, (m, n) => n + (n === '1' ? ' Sieg in Folge' : ' Siege in Folge'))
    .replace(/(\d+) days in a row/g, (m, n) => n + (n === '1' ? ' Tag in Folge' : ' Tage in Folge'));
}
/** "3 gelöst, 5 gespielt". */
function deI18nSolved(a, b) { return a + ' gelöst, ' + b + ' gespielt'; }
/** A row of Ask the odds: "2 Crispin", "1 von Arven oder Iono", "je 1 von Arven und Iono". */
function deI18nAsk(s) {
  return String(s).split(/, and (?=\d)/).map(r => {
    const m = /^(\d+) (each of |of )?(.+)$/.exec(r);
    if (!m) return r;
    const list = m[3].replace(/ or ([^,]+)$/, ' oder $1').replace(/ and ([^,]+)$/, ' und $1');
    return m[2] === 'each of ' ? 'je ' + m[1] + ' von ' + list : m[2] ? m[1] + ' von ' + list : m[1] + ' ' + list;
  }).join(' und ');
}
/** "Fire and Lightning Energy" (n of them) as "Feuer- und Elektro-Energie". */
function deI18nEnergy(w, n) {
  const ts = String(w).replace(/ Energy$/, '').split(/ and |, /).map(t => deI18nTypesE[t] || t);
  const noun = n != null && +n !== 1 ? 'Energien' : 'Energie', last = ts[ts.length - 1] + '-' + noun;
  return ts.length > 1 ? ts.slice(0, -2).map(t => t + '-, ').join('') + ts[ts.length - 2] + '- und ' + last : last;
}
/** A card group name in the compare table: a Basic Energy says its type in German, any other name stays. */
function deI18nCardOrEnergy(n) {
  const m = /^(Basic )?(\w+) Energy$/.exec(n);
  if (!m || !deI18nTypes[m[2]]) return n;
  return (m[1] ? 'Basis-' : '') + deI18nTypesE[m[2]] + '-Energie';
}

