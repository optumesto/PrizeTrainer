// Helpers for the Italian patterns, the same jobs as i18nEnergy, i18nWhen, i18nRuns, i18nSolved,
// i18nAsk and i18nCardOrEnergy in js/i18n.js (their es branch), written for Italian.
var itI18nTypes = { Grass: 'Erba', Fire: 'Fuoco', Water: 'Acqua', Lightning: 'Lampo', Psychic: 'Psico', Fighting: 'Lotta', Darkness: 'Oscurità', Metal: 'Metallo', Dragon: 'Drago', Colorless: 'Incolore', Fairy: 'Folletto' };
/** "Fire and Lightning Energy" (n of them) as "Energia Fuoco e Lampo". */
function itI18nEnergy(w, n) {
  const ts = String(w).replace(/ Energy$/, '').split(/ and |, /).map(t => itI18nTypes[t] || t);
  const many = n != null && +n !== 1;
  return (many ? 'Energie ' : 'Energia ') + (ts.length > 1 ? ts.slice(0, -1).join(', ') + ' e ' + ts[ts.length - 1] : ts[0]);
}
/** "Today, 3:00 PM", "Yesterday, ..." or a date, as the grade history writes them; null for anything else. */
function itI18nWhen(w) {
  const m = /^(Today|Yesterday), (.+)$/.exec(w);
  if (m) return (m[1] === 'Today' ? 'Oggi, ' : 'Ieri, ') + m[2];
  return /^(?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) \d{1,2}(?:, \d{4})?$/.test(w) ? w : null;
}
/** The puzzle streak words: "3 wins in a row, 4 days in a row". */
function itI18nRuns(s) {
  return s.replace(/(\d+) wins in a row/g, (m, n) => n + (n === '1' ? ' vittoria di fila' : ' vittorie di fila'))
    .replace(/(\d+) days in a row/g, (m, n) => n + (n === '1' ? ' giorno di fila' : ' giorni di fila'));
}
/** "3 solved of 5 played", as a label: "Risolti: 3 su 5". */
function itI18nSolved(a, b) {
  return 'Risolti: ' + a + ' su ' + b;
}
/** A row of Ask the odds: "2 Crispin", "1 of Arven or Iono", "1 each of Arven and Iono". */
function itI18nAsk(s) {
  return s.split(/, and (?=\d)/).map(r => {
    const m = /^(\d+) (each of |of )?(.+)$/.exec(r);
    if (!m) return r;
    const list = m[3].replace(/ or ([^,]+)$/, ' o $1').replace(/ and ([^,]+)$/, ' e $1');
    return m[2] === 'each of ' ? m[1] + ' di ognuna (' + list + ')' : m[2] ? m[1] + ' tra ' + list : m[1] + ' ' + list;
  }).join(', e ');
}
/** A card group name in the compare table: a Basic Energy says its type in Italian, any other name stays. */
function itI18nCardOrEnergy(n) {
  const m = /^(Basic )?(\w+) Energy$/.exec(n);
  if (!m || !itI18nTypes[m[2]]) return n;
  return itI18nEnergy(m[2]) + (m[1] ? ' di base' : '');
}
/** Capital first letter, for a sentence that starts with "il 45%" or "l'83%". */
function itI18nCap(s) { return s ? s[0].toUpperCase() + s.slice(1) : s; }
/** "16 Sep" or "6 Nov" (a day and month with no year, which the date pass leaves alone) as "16 set", "6 nov". */
function itI18nDm(s) {
  const en = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  return String(s).replace(/\b(\d{1,2}) (Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\b/g, (m, d, mo) => d + ' ' + I18N_MORE.it.mon3[en.indexOf(mo)]);
}
/** "a" before a month or year, "ad" before a vowel: "ad aprile 2027". */
function itI18nA(w) { return (/^[AEIOUaeiou]/.test(w) ? 'ad ' : 'a ') + w; }
/** il, al or dal before a date, elided before 8 and 11 ("l'8 nov", "dall'11 nov"); before a set name, "dall'uscita di". */
function itI18nDay(p, d) {
  if (!/\b(?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)/.test(d)) return (p === 'dal' ? "dall'uscita di" : p) + ' ' + d;
  const n = (/\b(\d{1,2})\b/.exec(d) || [])[1];
  return (n === '8' || n === '11' ? { il: "l'", al: "all'", dal: "dall'" }[p] : p + ' ') + d;
}
/** il, al, dal, nel or del before a number, elided before 8 and 11 ("l'80%", "dall'83%"). */
function itI18nNum(p, x) {
  return (/^(?:8|11(?!\d))/.test(x) ? { il: "l'", al: "all'", dal: "dall'", nel: "nell'", del: "dell'" }[p] : p + ' ') + x;
}

