var I18N_MORE = typeof I18N_MORE === 'object' && I18N_MORE ? I18N_MORE : {};

// French helpers for the patterns below, mirroring the Spanish branch of the helpers in js/i18n.js.
const FR_I18N_TYPES = { Grass: 'Plante', Fire: 'Feu', Water: 'Eau', Lightning: 'Électrique', Psychic: 'Psy', Fighting: 'Combat', Darkness: 'Obscurité', Metal: 'Métal', Dragon: 'Dragon', Colorless: 'Incolore', Fairy: 'Fée' };
/** "Today, 3:00 PM", "Yesterday, ..." or a date, as the grade history writes them; null for anything else. */
function frI18nWhen(w) {
  const m = /^(Today|Yesterday), (.+)$/.exec(w);
  if (m) return (m[1] === 'Today' ? "Aujourd'hui, " : 'Hier, ') + frI18nClock(m[2]);
  return /^(?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) \d{1,2}(?:, \d{4})?$/.test(w) ? frI18nDate(w) : null;
}
/** "3:00 PM" as "15:00", the 24 hour clock French uses; anything else stays. */
function frI18nClock(t) {
  const m = /^(\d{1,2}):(\d{2})\s?([AP])\.?M\.?$/i.exec(String(t).trim());
  if (!m) return t;
  const h = (+m[1] % 12) + (/p/i.test(m[3]) ? 12 : 0);
  return (h < 10 ? '0' : '') + h + ':' + m[2];
}
const FR_I18N_MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
/** English dates inside a text in French: "Nov 1, 2026" and "1 Nov 2026" as "1er nov. 2026", "16 Sep" as
 *  "16 sept.", "April 2027" as "avril 2027". The day 1 is "1er", as French writes it. */
function frI18nDate(s) {
  const x = I18N_MORE.fr, i = mo => FR_I18N_MONTHS.findIndex(y => y.startsWith(mo.slice(0, 3)));
  const day = d => +d === 1 ? '1er' : String(+d);
  const S = '(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]*';
  return String(s)
    .replace(new RegExp('\\b(' + FR_I18N_MONTHS.join('|') + ') (\\d{4})\\b', 'g'), (m, mo, y) => x.mon[i(mo)] + ' ' + y)
    .replace(new RegExp('\\b' + S + ' (\\d{1,2})(?:, (\\d{4}))?\\b', 'g'), (m, mo, d, y) => day(d) + ' ' + x.mon3[i(mo)] + (y ? ' ' + y : ''))
    .replace(new RegExp('\\b(\\d{1,2}) ' + S + '(?: (\\d{4}))?\\b', 'g'), (m, d, mo, y) => day(d) + ' ' + x.mon3[i(mo)] + (y ? ' ' + y : ''));
}
/** A sentence that ends on a date: one full stop, even after an abbreviated month ("6 nov."). */
function frI18nDot(s) { return /\.$/.test(s) ? s : s + '.'; }
/** 1,597 as 1 597 (a no-break space): in French a comma is the decimal mark, so 1,597 would read as 1.597. */
function frI18nNum(n) { return String(n); }   // 3.3.2: rdI18n puts every number in French form
/** The puzzle streak words: "3 wins in a row, 4 days in a row". */
function frI18nRuns(s) {
  return s.replace(/(\d+) wins in a row/g, (m, n) => n + (n === '1' ? " victoire d'affilée" : " victoires d'affilée"))
    .replace(/(\d+) days in a row/g, (m, n) => n + (n === '1' ? " jour d'affilée" : " jours d'affilée"));
}
/** "3 solved of 5 played", with the words in the singular for 1. */
function frI18nSolved(a, b) {
  return a + (a === '1' ? ' résolu sur ' : ' résolus sur ') + b + (b === '1' ? ' joué' : ' joués');
}
/** A row of Ask the odds: "2 Crispin", "1 of Arven or Iono", "1 each of Arven and Iono". */
function frI18nAsk(s) {
  return s.split(/, and (?=\d)/).map(r => {
    const m = /^(\d+) (each of |of )?(.+)$/.exec(r);
    if (!m) return r;
    const list = m[3].replace(/ or ([^,]+)$/, ' ou $1').replace(/ and ([^,]+)$/, ' et $1');
    return m[2] === 'each of ' ? m[1] + ' de chaque (' + list + ')' : m[2] ? m[1] + ' parmi ' + list : m[1] + ' ' + list;
  }).join(', et ');
}
/** "Fire and Lightning Energy" (n of them) as "Énergie Feu et Électrique". */
function frI18nEnergy(w, n) {
  const ts = String(w).replace(/ Energy$/, '').split(/ and |, /).map(t => FR_I18N_TYPES[t] || t);
  const many = n != null && +n !== 1;
  return (many ? 'Énergies ' : 'Énergie ') + (ts.length > 1 ? ts.slice(0, -1).join(', ') + ' et ' + ts[ts.length - 1] : ts[0]);
}
/** A card group name in the compare table: a Basic Energy says its type in French, any other name stays. */
function frI18nCardOrEnergy(n) {
  const m = /^(Basic )?(\w+) Energy$/.exec(n);
  if (!m || !FR_I18N_TYPES[m[2]]) return n;
  return frI18nEnergy(m[2]) + (m[1] ? ' de base' : '');
}
/** "1st" or "1" as "1re place", "2nd" as "2e place". */
function frI18nPlace(p) {
  const n = String(parseInt(p, 10));
  return (n === '1' ? '1re' : n + 'e') + ' place';
}

