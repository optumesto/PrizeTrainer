#!/usr/bin/env node
// Copies Goldfish's card text reader out of index.html into puzzle/text.js, word for word,
// so puzzle mode and Goldfish read card text the same way. Run it after any change to
// these functions in index.html:   node puzzle/tools/sync-text.mjs
// With --check it only reports whether puzzle/text.js still matches index.html (used by the tests).
//
// Later (rules core phase), index.html drops its own copies and loads puzzle/text.js instead,
// and this script is deleted.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SRC = join(root, 'index.html');
const OUT = join(root, 'puzzle', 'text.js');

// Pure functions only: each reads card text or a card, never Goldfish's board (gf).
export const NAMES = [
  'GF_TY', 'GF_ELET', 'gfNorm', 'gfSubs', 'gfIsEx', 'gfIsMega', 'gfRuleBox', 'gfTypes', 'gfEType', 'gfFit',
  'gfPhrase', 'gfThing', 'gfThings', 'gfMaxOf', 'gfSlotsOk', 'gfSpecFits', 'gfSentences', 'gfStadiumText',
  'gfParseBody', '_gfTP', 'gfTrainerPlay', '_gfAP', 'GF_PRE', 'gfAbilities', 'gfIsBasic', 'gfIsEvo', 'gfKey',
];

export function extract(html) {
  const lines = html.split('\n');
  const out = {};
  for (const name of NAMES) {
    const fi = lines.findIndex(l => l.startsWith('function ' + name + '('));
    if (fi >= 0) {
      // A one-line function ends on its own line; otherwise run to the first "}" at column 0.
      let end = fi;
      if (!/^function [^{]+\{.*\}\s*$/.test(lines[fi])) { end = fi + 1; while (end < lines.length && lines[end] !== '}') end++; }
      out[name] = lines.slice(fi, end + 1).join('\n');
      continue;
    }
    const ci = lines.findIndex(l => l.startsWith('const ' + name + ' ='));
    if (ci >= 0 && /;\s*$/.test(lines[ci])) { out[name] = lines[ci]; continue; }
    throw new Error('Not found as a top-level function or one-line const in index.html: ' + name);
  }
  return out;
}

export function build(html) {
  const parts = extract(html);
  const body = NAMES.map(n => parts[n]).join('\n');
  return `// GENERATED by puzzle/tools/sync-text.mjs from index.html. Do not edit by hand.
// Goldfish's card text reader, word for word, so puzzles read cards exactly as Goldfish does.
// It needs four card helpers from its host: cardCategory, gfInfo, gfKind and cn23.
// puzzle/engine.js supplies them for puzzle cards; index.html has its own.
(function (root) {
'use strict';
function makeText(host) {
const { cardCategory, gfInfo, gfKind, cn23 } = host;
${body}
return { ${NAMES.join(', ')} };
}
root.RdyPuzzleText = makeText;
if (typeof module !== 'undefined' && module.exports) module.exports = makeText;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const html = readFileSync(SRC, 'utf8');
  const next = build(html);
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = readFileSync(OUT, 'utf8'); } catch (_) {}
    if (cur !== next) { console.error('puzzle/text.js is out of date with index.html. Run: node puzzle/tools/sync-text.mjs'); process.exit(1); }
    console.log('puzzle/text.js matches index.html');
  } else {
    writeFileSync(OUT, next);
    console.log('Wrote puzzle/text.js (' + NAMES.length + ' pieces)');
  }
}
